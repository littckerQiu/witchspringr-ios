#!/usr/bin/env python3
# games/<id>/game.json → C profile for the host (host/game.h: dm_game). Also prints single fields for shell scripts.
# Usage: gen_game.py <game.json> <out.c>        write the profile source
#        gen_game.py <game.json> --get <key>    print a field (lists joined by spaces), e.g. --get modules
import json, re, sys

REQUIRED = ('id', 'title', 'version', 'engine', 'program_id', 'modules', 'main_build_id', 'language', 'screen', 'romfs')

def load(path):
    g = json.load(open(path, encoding='utf-8'))
    miss = [k for k in REQUIRED if k not in g]
    if miss: sys.exit(f'{path}: missing {", ".join(miss)}')
    if not isinstance(g['screen'], list) or len(g['screen']) != 2: sys.exit(f'{path}: screen must be [width, height]')
    int(g['program_id'], 16); bytes.fromhex(g['main_build_id'])
    if not re.fullmatch(r'\d+\.\d+', g.get('device_api', '55.15')): sys.exit(f'{path}: device_api must be "major.minor"')
    c2 = g.get('nvn_c2')
    if not isinstance(c2, dict) or sorted(c2) != ['img', 'samp', 'tex'] or not all(isinstance(v, list) and len(v) == 2 and re.fullmatch(r'0x[0-9a-fA-F]+', str(v[0])) and isinstance(v[1], int) for v in c2.values()):
        sys.exit(f'{path}: nvn_c2 must be {{"tex": ["0x..", slots], "samp": ["0x..", slots], "img": ["0x..", slots]}}')
    if max(int(v[0], 16) + 8 * v[1] for v in c2.values()) > 0xA00: sys.exit(f'{path}: nvn_c2 tables must end within 0xA00 (the replay layer fills a 0xA00-byte bank)')
    if g.get('depth_mode') not in ('near_is_minus_w', 'near_is_zero'): sys.exit(f'{path}: depth_mode must be "near_is_minus_w" or "near_is_zero"')
    if g.get('alpha_test', 'off') not in ('on', 'off'): sys.exit(f'{path}: alpha_test must be "on" or "off" (omitted: off)')
    if g.get('present_interval', 'display') not in ('display', 'game'): sys.exit(f'{path}: present_interval must be "display" or "game"')
    if g.get('window_unfocused', 'out_of_focus') not in ('out_of_focus', 'in_focus'): sys.exit(f'{path}: window_unfocused must be "out_of_focus" or "in_focus"')
    if not isinstance(g.get('virtual_cores', False), bool): sys.exit(f'{path}: virtual_cores must be true or false')
    if g.get('touch', 'screen') not in ('screen', 'pad'): sys.exit(f'{path}: touch must be "screen" or "pad"')
    return g

def cstr(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'

# workspace keys the host uses as command-line defaults: (profile field, game.json workspace key)
WS_FIELDS = (('romfs', 'romfs'), ('sysfont', 'sysfont'), ('product', 'product'), ('shader_map', 'shader_map'), ('msl', 'msl_mac'))

def write_c(g, out):
    ws = g.get('workspace', {})
    r = g['romfs']; files = r.get('files', {}); sync = g.get('save_sync', []); aoc = [int(i) for i in g.get('aoc', [])]
    L = ['// Generated by tools/gen_game.py from games/%s/game.json; do not edit.' % g['id'], '#include "game.h"', '']
    L.append('static const dm_game_file romfs_files[] = {' + ''.join(f'{{{cstr(p)}, {n}LL}}, ' for p, n in files.items()) + '{0, 0}};')
    L.append('static const char *const save_sync[] = {' + ''.join(cstr(p) + ', ' for p in sync) + '0};')
    L.append('static const int aoc[] = {' + ''.join(f'{i}, ' for i in aoc) + '0};')
    L += ['const dm_game_profile dm_game = {',
          f'    .id = {cstr(g["id"])}, .title = {cstr(g["title"])}, .version = {cstr(g["version"])}, .engine = {cstr(g["engine"])},',
          f'    .program_id = 0x{int(g["program_id"], 16):016x}ull,',
          f'    .modules = {cstr(" ".join(g["modules"]))}, .main_build_id = {cstr(g["main_build_id"])}, .language = {cstr(g["language"])},',
          f'    .screen_w = {g["screen"][0]}, .screen_h = {g["screen"][1]}, .guest_heap_mb = {g.get("guest_heap_mb", 256)},',
          '    .nvn_api_major = %s, .nvn_api_minor = %s,' % tuple(g.get('device_api', '55.15').split('.')),
          '    .nvn_c2 = {%s},' % ', '.join(f'{v[0]}, {v[1]}' for v in (g['nvn_c2']['tex'], g['nvn_c2']['samp'], g['nvn_c2']['img'])),
          '    .nvn_depth_mode = %d,' % (1 if g['depth_mode'] == 'near_is_zero' else 0),
          '    .present_game_interval = %d,' % (g.get('present_interval', 'display') == 'game'),
          '    .unfocused_in_focus = %d,' % (g.get('window_unfocused', 'out_of_focus') == 'in_focus'),
          '    .virtual_cores = %d,' % bool(g.get('virtual_cores', False)),
          '    .touch_pad = %d,' % (g.get('touch', 'screen') == 'pad'),
          f'    .romfs_files = romfs_files, .romfs_nfiles = {len(files)},',
          f'    .romfs_tree = {cstr(r["tree"]) if r.get("tree") else "0"}, .romfs_tree_files = {r.get("tree_files", 0)}, .romfs_tree_bytes = {r.get("tree_bytes", 0)}LL,',
          f'    .save_sync = save_sync, .save_sync_n = {len(sync)},',
          f'    .aoc = aoc, .aoc_n = {len(aoc)},',
          '    .ws = {' + ', '.join(f'.{f} = {cstr(ws[k]) if ws.get(k) else "0"}' for f, k in WS_FIELDS) + '},',
          '};', '']
    open(out, 'w', encoding='utf-8').write('\n'.join(L))

if __name__ == '__main__':
    g = load(sys.argv[1])
    if sys.argv[2] == '--get':
        v = g
        for k in sys.argv[3].split('.'): v = v[k]
        print(' '.join(map(str, v)) if isinstance(v, list) else v)
    else: write_c(g, sys.argv[2])
